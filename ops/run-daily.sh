#!/usr/bin/env bash
#
# Обёртка запуска дайджеста под cron.
#
# Зачем она есть. Раньше вся конфигурация жила одной длинной строкой в crontab.
# С появлением трёх заходов за утро эта строка размножилась бы втрое, и любая
# правка (смена бота, нового источника) требовала бы синхронно поменять три
# копии — расхождение между ними не заметил бы никто.
#
# Имена секретов лежат в /etc/ai-dev-daily/ai-dev-daily.env, а НЕ здесь: файл
# в репозитории раскрыл бы карту инфраструктуры (какой vault, какие ключи), и
# это сознательное решение из config.py. Здесь только механика запуска.
# Значений секретов нет нигде — их отдаёт Key Vault по managed identity.
#
# Использование:  ops/run-daily.sh --attempt 1 --attempts 3

set -euo pipefail

ENV_FILE="${AI_DEV_DAILY_ENV_FILE:-/etc/ai-dev-daily/ai-dev-daily.env}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

if [[ ! -r "$ENV_FILE" ]]; then
  # Явная диагностика: без неё прогон упал бы внутри Python на «нет ключа»,
  # и причину искали бы в Key Vault, а не в отсутствующем файле на хосте.
  echo "ai-dev-daily: не читается $ENV_FILE — конфигурация запуска не найдена" >&2
  exit 78            # EX_CONFIG
fi

# shellcheck disable=SC1090
set -a; source "$ENV_FILE"; set +a

# Потолок на процесс. Внутри есть свой таймаут, но он не спасает от зависания
# в неожиданном месте (в первую очередь — `az` без интерактивной сессии).
# Висящий процесс держит lock и молча съедает утро: следующий заход увидит
# живого владельца lock и по правилу не станет его отбирать.
#
# SIGTERM прогон обрабатывает сам (install_termination_handler): пишет отметку
# failure и шлёт алёрт обычным путём. Минуты до KILL на это хватает.
#
# Без `exec` намеренно: нужно увидеть статус. Если дело всё-таки дошло до
# неперехватываемого KILL, записать исход уже некому — и тогда единственный
# след останется здесь, в логе. Молчание в этом месте выглядело бы как
# нормальное завершение.
set +e
timeout --signal=TERM --kill-after=60s 15m \
  "$REPO_ROOT/.venv/bin/python" "$REPO_ROOT/pipeline/run_daily.py" "$@"
status=$?
set -e

if [[ $status -eq 124 || $status -eq 137 ]]; then
  echo "ai-dev-daily: прогон снят по таймауту (код $status)" >&2
fi
exit "$status"
